"""基础内容包的文本总表（lang）：**所有面向玩家的文字都住这里**，别处只引用、不写字面量。

约定
----
- **扁平字典**：`TEXT["<模块>.<语义>"]`；键用 `.` 分层、小写，语义自己起（不按行号）。
- **模板**：f-string 的动态部分写成 `{名字}`，调用处 `TEXT["…"].format(名字=…)`；
  带格式的照写（`{amount:g}` → `.format(amount=…)`）。
- **只放文字**：数据键（`path` / `source` / tag / 性别 / 年龄 / 兴趣）**不搬**——
  它们参与规则命中，禁止翻译（见 `docs/ROADMAP.md` §7 的三类字符串）。
- **内容层的键用既有 id 拼**：`ability.<ability_id>.desc`、`item.<item_id>.name` …
  随定义走，不用另起一套名字。
- **一个包一个文件**：base 就是本文件；每个 DLC 自己带 `dlc/<包>/lang.py`。
  不做可插拔语言包、不做回退链（已定，见 `docs/DECISIONS.md`）。

检索/搬运都用 `python tools/dump_text.py`（同一份语料）。
"""

from __future__ import annotations

# DLC 的文字各住自己的 `dlc/<包>/lang.py`；包自己的模块写
# `TEXT = pack_text_from_file(__file__)` 就能拿到。base 的模块直接用下面的 `TEXT`。
PACK_TEXT: dict[str, dict[str, str]] = {}


def pack_text_from_file(file: str) -> dict[str, str]:
    """按文件所属的 DLC 目录取该包的文字表（按包缓存；包没带 lang 就回落到空表）。"""
    from pathlib import Path

    parts = Path(file).resolve().parts
    if "dlc" not in parts:
        return TEXT
    index = parts.index("dlc")
    pack = parts[index + 1]
    if pack not in PACK_TEXT:
        PACK_TEXT[pack] = _load_lang_file(Path(*parts[:index + 2]) / "lang.py", pack)
    return PACK_TEXT[pack]


def _load_lang_file(path, pack: str) -> dict[str, str]:
    import importlib.util

    if not path.is_file():
        return {}
    spec = importlib.util.spec_from_file_location("_dlc_lang_" + pack, path)
    if spec is None or spec.loader is None:
        return {}
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return dict(getattr(module, "TEXT", {}))


def source_label(token: str) -> str:
    """把匹配令牌换成**日志显示名**（`source.<token>`）；没登记的令牌原样返回。

    令牌是程序标识（英文，见 `docs/ARCH.md` §4），玩家看到的仍是中文——
    所以日志/界面渲染一律走这里，不要把令牌直接插进文案。
    """
    return TEXT.get("source." + token, token)


def token_label(token: str) -> str:
    """把数值变化令牌（`consume` / `damage` / `loss` / `restore`）换成显示名。"""
    return TEXT.get("token." + token, token)


